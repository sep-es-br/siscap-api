
CREATE TABLE indicador_avulso (
    id                  SERIAL CONSTRAINT pk_indicador_avulso PRIMARY KEY,
    nome_indicador      VARCHAR(2000) NOT NULL,
    unidade_medida      VARCHAR(2000) NOT NULL,
    fonte_indicador     VARCHAR(2000) NOT NULL,
    medido_por          VARCHAR(2000) NOT NULL,
    base_de_referencia  VARCHAR(2000) NOT NULL,
    apagado             BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em           TIMESTAMP NOT NULL,
    atualizado_em       TIMESTAMP NOT NULL
);

CREATE TABLE indicador_avulso_meta (
    id                      SERIAL CONSTRAINT pk_indicador_avulso_meta PRIMARY KEY,
    id_indicador_avulso     INTEGER NOT NULL,
    ano                     INTEGER NOT NULL,
    valor                   VARCHAR(255) NOT NULL,
    apagado                 BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em               TIMESTAMP NOT NULL,
    atualizado_em           TIMESTAMP NOT NULL
);

ALTER TABLE indicador_avulso_meta
    ADD CONSTRAINT fk_indicador_avulso_meta_indicador
    FOREIGN KEY (id_indicador_avulso)
    REFERENCES indicador_avulso(id);

