    ADD CONSTRAINT fk_projeto_indicador_avulso_indicador
    FOREIGN KEY (id_indicador_avulso)
    REFERENCES indicador_avulso(id);

---------------------------------------------------------

CREATE TABLE projeto_indicador_avulso_meta (
    id                                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_projeto_indicador_avulso         INTEGER NOT NULL,
    ano                                 INTEGER NOT NULL,
    valor                               VARCHAR(255) NOT NULL,
    apagado                             BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em                           TIMESTAMP,
    atualizado_em                       TIMESTAMP
);

ALTER TABLE projeto_indicador_avulso_meta
    ADD CONSTRAINT fk_projeto_indicador_avulso_meta
    FOREIGN KEY (id_projeto_indicador_avulso)
    REFERENCES projeto_indicador_avulso(id);

-- criar indices para as FK´s
CREATE INDEX idx_indicador_avulso_meta_indicador
